final RegExp _simorghGradeControls = RegExp(
  r'[\u061C\u200B\u200E\u200F\u202A-\u202E\u2060\u2066-\u2069\uFEFF]',
);

final RegExp _simorghGradeWhitespace = RegExp(r'\s+');

/// Normalizes spelling for exact comparison, without inferring a grade.
String _normalizeSimorghGrade(String value) {
  return value
      .replaceAll('ي', 'ی')
      .replaceAll('ك', 'ک')
      // Preserve the word boundary in «دانش‌آموز».
      .replaceAll('\u200C', ' ')
      .replaceAll(_simorghGradeControls, '')
      .replaceAll(_simorghGradeWhitespace, ' ')
      .trim();
}

/// Validates and reserializes an object-shaped JSON profile.
///
/// Invalid, non-object or oversized input becomes an empty profile.
/// Never truncate serialized JSON: truncation can invalidate its structure.
///
/// This cap is an application-level size limit, not a token limit.
const int _maxSimorghProfileCharacters = 16000;

String _escapeProfileContext(String value) {
  if (value.length > _maxSimorghProfileCharacters) {
    return '{}';
  }

  final text = value.trim();
  if (text.isEmpty) return '{}';

  try {
    final Object? decoded = jsonDecode(text);

    if (decoded is! Map<String, dynamic>) {
      return '{}';
    }

    final encoded = jsonEncode(decoded);

    // Encode delimiter characters inside the valid JSON representation.
    // These are single-backslash JSON Unicode escapes.
    final escaped = encoded
        .replaceAll('&', r'\u0026')
        .replaceAll('<', r'\u003c')
        .replaceAll('>', r'\u003e');

    if (escaped.length > _maxSimorghProfileCharacters) {
      return '{}';
    }

    return escaped;
  } on FormatException {
    return '{}';
  }
}
